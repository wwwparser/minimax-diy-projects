def short(line) -> str:
    return SHORT.get(line["code"]) or re.split(r" сорт| \(|,", line["title"])[0][:30]

def short_step(s: str, n: int = 44) -> str:
    s = re.split(r"[:;(]| — ", s)[0].strip().rstrip(".")
    if len(s) <= n:
        return s
    cut = s[:n].rsplit(" ", 1)[0]
    return cut.rstrip(",")
